using System.Globalization;
using Kaminari.Seseragi.Lakehouse.Delta.Actions;
using Kaminari.Seseragi.Lakehouse.Delta.Schema;

namespace Kaminari.Seseragi.Lakehouse.Delta;

/// <summary>
/// An identity column (the <c>identityColumns</c> writer feature): a <c>long</c> column whose values the writer
/// generates, <c>start</c>, <c>start + step</c>, …, beyond the highest (or, stepping down, lowest) value generated so
/// far, its high water mark.
/// </summary>
/// <param name="Name">The column's logical name.</param>
/// <param name="Start">The first value.</param>
/// <param name="Step">The distance between values; never 0.</param>
/// <param name="HighWaterMark">The last value generated; null before the first.</param>
/// <param name="AllowExplicitInsert">GENERATED BY DEFAULT: rows may bring their own value (kept as given, the high
/// water mark unchanged). False for GENERATED ALWAYS.</param>
public sealed record IdentityColumn(string Name, long Start, long Step, long? HighWaterMark, bool AllowExplicitInsert)
{
    /// <summary>The value the next generated row gets.</summary>
    /// <exception cref="DeltaException">The next value is beyond the range of a long.</exception>
    public long NextValue => HighWaterMark is long mark ? Advance(mark, 1) : Start;

    /// <summary>The value <paramref name="count"/> steps after <paramref name="from"/>.</summary>
    /// <exception cref="DeltaException">The value is beyond the range of a long.</exception>
    public long Advance(long from, long count)
    {
        try
        {
            return checked(from + Step * count);
        }
        catch (OverflowException)
        {
            throw new DeltaException($"The identity column '{Name}' has run out of values: the next ones are beyond the range of a long.");
        }
    }
}

/// <summary>Reading identity columns from a schema and recording the values a write generated.</summary>
public static class IdentityColumns
{
    /// <summary>The field metadata key of the first value.</summary>
    public const string StartKey = "delta.identity.start";
    /// <summary>The field metadata key of the step.</summary>
    public const string StepKey = "delta.identity.step";
    /// <summary>The field metadata key of the high water mark.</summary>
    public const string HighWaterMarkKey = "delta.identity.highWaterMark";
    /// <summary>The field metadata key telling GENERATED BY DEFAULT (true) from GENERATED ALWAYS (false).</summary>
    public const string AllowExplicitInsertKey = "delta.identity.allowExplicitInsert";

    /// <summary>The identity columns of a schema (top-level columns only, as Delta allows them).</summary>
    /// <exception cref="DeltaProtocolException">An identity column is not a long, or its metadata is incomplete.</exception>
    public static IReadOnlyList<IdentityColumn> Of(StructType schema)
    {
        ArgumentNullException.ThrowIfNull(schema);
        var result = new List<IdentityColumn>();
        foreach (StructField field in schema.Fields)
        {
            if (!field.Metadata.Keys.Any(k => k.StartsWith("delta.identity.", StringComparison.Ordinal))) continue;
            if (field.Type is not PrimitiveType { Name: PrimitiveType.Long })
                throw new DeltaProtocolException($"The identity column '{field.Name}' is of type {field.Type}, not long.");
            long start = Long(field, StartKey) ?? throw Incomplete(field, StartKey);
            long step = Long(field, StepKey) ?? throw Incomplete(field, StepKey);
            if (step == 0) throw new DeltaProtocolException($"The identity column '{field.Name}' has a step of 0.");
            bool explicitInsert = field.Metadata.TryGetValue(AllowExplicitInsertKey, out string? allow)
                ? bool.TryParse(allow, out bool b) ? b : throw new DeltaProtocolException($"The identity column '{field.Name}' has {AllowExplicitInsertKey} = '{allow}'.")
                : throw Incomplete(field, AllowExplicitInsertKey);
            result.Add(new IdentityColumn(field.Name, start, step, Long(field, HighWaterMarkKey), explicitInsert));
        }
        return result;

        static DeltaProtocolException Incomplete(StructField field, string key) =>
            new($"The identity column '{field.Name}' has no {key}.");
    }

    private static long? Long(StructField field, string key)
    {
        if (!field.Metadata.TryGetValue(key, out string? text)) return null;
        return long.TryParse(text, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out long value)
            ? value
            : throw new DeltaProtocolException($"The identity column '{field.Name}' has {key} = '{text}', which is not a long.");
    }

    /// <summary>
    /// The field declared an identity column (no value generated yet), with the metadata Spark writes for
    /// <c>GENERATED ALWAYS | BY DEFAULT AS IDENTITY (START WITH start INCREMENT BY step)</c>.
    /// </summary>
    /// <exception cref="DeltaException">The field is not a long, or the step is 0.</exception>
    public static StructField Declare(StructField field, long start, long step, bool allowExplicitInsert)
    {
        ArgumentNullException.ThrowIfNull(field);
        if (field.Type is not PrimitiveType { Name: PrimitiveType.Long })
            throw new DeltaException($"The identity column '{field.Name}' must be a long (Int64), not {field.Type}.");
        if (step == 0) throw new DeltaException($"The identity column '{field.Name}' cannot step by 0.");
        var metadata = new Dictionary<string, string>(field.Metadata, StringComparer.Ordinal)
        {
            [StepKey] = step.ToString(CultureInfo.InvariantCulture),
            [AllowExplicitInsertKey] = allowExplicitInsert ? "true" : "false",
            [StartKey] = start.ToString(CultureInfo.InvariantCulture),
        };
        return new StructField
        {
            Name = field.Name,
            Type = field.Type,
            Nullable = field.Nullable,
            Metadata = metadata,
            JsonMetadataKeys = new HashSet<string>(field.JsonMetadataKeys) { StepKey, AllowExplicitInsertKey, StartKey },
        };
    }

    /// <summary>
    /// The metadata with new high water marks for the named identity columns (written as JSON numbers, as Spark
    /// writes them); everything else as it was.
    /// </summary>
    public static MetadataAction WithHighWaterMarks(MetadataAction metadata, IReadOnlyDictionary<string, long> marks)
    {
        ArgumentNullException.ThrowIfNull(metadata);
        ArgumentNullException.ThrowIfNull(marks);
        if (marks.Count == 0) return metadata;
        StructType schema = StructType.Parse(metadata.SchemaString);
        var fields = schema.Fields.Select(field =>
        {
            if (!marks.TryGetValue(field.Name, out long mark)) return field;
            var values = new Dictionary<string, string>(field.Metadata, StringComparer.Ordinal)
            {
                [HighWaterMarkKey] = mark.ToString(CultureInfo.InvariantCulture),
            };
            return new StructField
            {
                Name = field.Name,
                Type = field.Type,
                Nullable = field.Nullable,
                Metadata = values,
                JsonMetadataKeys = new HashSet<string>(field.JsonMetadataKeys) { HighWaterMarkKey },
            };
        }).ToList();
        return WithSchema(metadata, new StructType(fields).ToJson());
    }

    /// <summary>
    /// <paramref name="target"/> with the high water marks of <paramref name="current"/> wherever both have the
    /// identity column: a restore must not hand out values again that the table has given already.
    /// </summary>
    public static MetadataAction KeepHighWaterMarks(MetadataAction target, MetadataAction current)
    {
        ArgumentNullException.ThrowIfNull(target);
        ArgumentNullException.ThrowIfNull(current);
        var now = Of(StructType.Parse(current.SchemaString)).Where(c => c.HighWaterMark is not null).ToDictionary(c => c.Name, c => c.HighWaterMark!.Value);
        var marks = Of(StructType.Parse(target.SchemaString))
            .Where(c => now.TryGetValue(c.Name, out long mark) && c.HighWaterMark != mark)
            .ToDictionary(c => c.Name, c => now[c.Name]);
        return WithHighWaterMarks(target, marks);
    }

    private static MetadataAction WithSchema(MetadataAction m, string schemaString) => new()
    {
        Id = m.Id, Name = m.Name, Description = m.Description, FormatProvider = m.FormatProvider, FormatOptions = m.FormatOptions,
        SchemaString = schemaString, PartitionColumns = m.PartitionColumns, Configuration = m.Configuration, CreatedTime = m.CreatedTime,
    };
}
