using Kaminari.Seseragi.Lakehouse.Engine;
using Polars.NET.Core.Exceptions;

namespace Polars.NET.Core.Delta;

/// <summary>An identity column to declare when a table is created.</summary>
/// <param name="Column">The column; it must be a long (Int64) column of the schema, not a partition column.</param>
/// <param name="Start">The first value.</param>
/// <param name="Step">The distance between values; not 0 (negative counts down).</param>
/// <param name="GeneratedAlways">GENERATED ALWAYS (rows never bring their own value); false for GENERATED BY
/// DEFAULT (rows may bring one).</param>
internal sealed record KernelIdentityColumn(string Column, long Start = 1, long Step = 1, bool GeneratedAlways = true);

/// <summary>
/// Creates an empty Delta table, as Spark's <c>CREATE TABLE</c>: version 0 with the schema, partitioning, table
/// properties and identity columns given. The public Delta API calls it.
/// </summary>
internal static class DeltaKernelCreate
{
    /// <summary>Version 0 of a table as committed: its metadata, protocol, domains and in-commit timestamp.</summary>
    public sealed record CreatedTable(MetadataAction Metadata, ProtocolAction Protocol, IReadOnlyList<DomainMetadataAction> Domains, long Timestamp);

    /// <summary>Creates the table; returns its version, 0.</summary>
    /// <param name="tablePath">The table location: a local directory or a cloud URL.</param>
    /// <param name="schema">The columns.</param>
    /// <param name="partitionBy">Partition columns; null for none.</param>
    /// <param name="configuration">Table properties (they bring the features they turn on); null for none.</param>
    /// <param name="identity">Identity columns; null for none.</param>
    /// <param name="cloud">Cloud settings for a cloud URL.</param>
    /// <param name="clusterBy">Liquid clustering columns (dotted for nested fields); null for none.</param>
    /// <param name="generated">Generated columns; null for none.</param>
    /// <param name="defaults">Column defaults; null for none.</param>
    /// <exception cref="PolarsException">A table exists at the path, or the declaration is not valid.</exception>
    public static long Create(
        string tablePath, StructType schema, string[]? partitionBy = null, IReadOnlyDictionary<string, string>? configuration = null,
        IReadOnlyList<KernelIdentityColumn>? identity = null, CloudArgs? cloud = null, string[]? clusterBy = null,
        IReadOnlyList<DeltaGeneratedColumn>? generated = null, IReadOnlyList<DeltaColumnDefault>? defaults = null) =>
        CreateCore(tablePath, schema, partitionBy, configuration, identity, cloud, clusterBy, features: null, generated, defaults);

    /// <summary>
    /// Replaces a table's definition, as Spark's <c>REPLACE TABLE</c> (<paramref name="orCreate"/>: <c>CREATE OR REPLACE
    /// TABLE</c>): one commit with the new schema, partitioning, clustering, properties and declarations, removing every
    /// data file. The history stays (time travel reads the old definition), the protocol is never lowered, and the
    /// properties Spark carries over are kept: deletion vectors and row tracking turned on (the row ids go on). Returns
    /// the version committed.
    /// </summary>
    /// <param name="orCreate">Create the table when there is none; otherwise that is refused.</param>
    /// <exception cref="PolarsException">There is no table to replace (without <paramref name="orCreate"/>), or the
    /// declaration is not valid.</exception>
    public static long Replace(
        string tablePath, StructType schema, string[]? partitionBy, IReadOnlyDictionary<string, string>? configuration,
        IReadOnlyList<KernelIdentityColumn>? identity, CloudArgs? cloud, string[]? clusterBy,
        IReadOnlyList<DeltaGeneratedColumn>? generated, IReadOnlyList<DeltaColumnDefault>? defaults, bool orCreate) =>
        CreateCore(tablePath, schema, partitionBy, configuration, identity, cloud, clusterBy, features: null, generated, defaults,
            orCreate ? Replacing.OrCreate : Replacing.Replace);

    private enum Replacing { No, Replace, OrCreate }

    /// <summary>
    /// Creates version 0 of a catalog-managed table at the location its catalog staged, as Delta Spark writes it (a
    /// published commit); returns what that version holds, from which the caller registers the table with the
    /// catalog.
    /// </summary>
    /// <param name="location">The staged location.</param>
    /// <param name="schema">The columns.</param>
    /// <param name="partitionBy">Partition columns; null for none.</param>
    /// <param name="configuration">Table properties, the catalog's included.</param>
    /// <param name="identity">Identity columns; null for none.</param>
    /// <param name="cloud">Cloud settings (the catalog's credentials) for a cloud URL.</param>
    /// <param name="clusterBy">Liquid clustering columns; null for none.</param>
    /// <param name="features">Table features the catalog asks for, on top of those the schema and properties bring
    /// (<see cref="TableFeatures.CatalogManaged"/> among them).</param>
    /// <param name="generated">Generated columns; null for none.</param>
    /// <param name="defaults">Column defaults; null for none.</param>
    /// <param name="orReplace">Created by <c>CREATE OR REPLACE TABLE</c> (the operation version 0 records).</param>
    /// <exception cref="PolarsException">A table exists at the location, or the declaration is not valid.</exception>
    public static CreatedTable CreateCatalogManaged(
        string location, StructType schema, string[]? partitionBy, IReadOnlyDictionary<string, string> configuration,
        IReadOnlyList<KernelIdentityColumn>? identity, CloudArgs? cloud, string[]? clusterBy, IReadOnlyList<string> features,
        IReadOnlyList<DeltaGeneratedColumn>? generated = null, IReadOnlyList<DeltaColumnDefault>? defaults = null, bool orReplace = false)
    {
        ArgumentNullException.ThrowIfNull(features);
        CreateCore(location, schema, partitionBy, configuration, identity, cloud, clusterBy, features, generated, defaults,
            orReplace ? Replacing.OrCreate : Replacing.No);
        return Version0(location, cloud);
    }

    /// <summary>What version 0 of the table at <paramref name="location"/> holds, as committed.</summary>
    public static CreatedTable Version0(string location, CloudArgs? cloud)
    {
        IWritableFileSystem store = TableStorage.Open(location, cloud).Store;
        try
        {
            IReadOnlyList<DeltaAction> actions = ActionParser.ParseFile(store, LogFile.CommitPath(0))
                ?? throw new PolarsException($"Version 0 of the table at {location} was not written.");
            CommitInfoAction info = actions.OfType<CommitInfoAction>().Single();
            return new CreatedTable(
                actions.OfType<MetadataAction>().Single(),
                actions.OfType<ProtocolAction>().Single(),
                [.. actions.OfType<DomainMetadataAction>()],
                info.InCommitTimestamp ?? throw new PolarsException("Version 0 of a catalog-managed table has no in-commit timestamp."));
        }
        finally
        {
            (store as IDisposable)?.Dispose();
        }
    }

    private static long CreateCore(
        string tablePath, StructType schema, string[]? partitionBy, IReadOnlyDictionary<string, string>? configuration,
        IReadOnlyList<KernelIdentityColumn>? identity, CloudArgs? cloud, string[]? clusterBy, IReadOnlyList<string>? features,
        IReadOnlyList<DeltaGeneratedColumn>? generated, IReadOnlyList<DeltaColumnDefault>? defaults, Replacing replacing = Replacing.No)
    {
        ArgumentNullException.ThrowIfNull(schema);
        if (schema.Fields.Count == 0) throw new PolarsException("A table needs at least one column.");
        string[] partitions = partitionBy ?? [];
        identity ??= [];
        IWritableFileSystem store = TableStorage.Open(tablePath, cloud).Store;
        try
        {
            Snapshot? existing = DeltaKernelWrite.TryLoad(store, tablePath, cloud);
            if (existing is not null && replacing == Replacing.No)
                throw new PolarsException($"Table already exists at {tablePath} (a Delta table).");
            if (existing is null && replacing == Replacing.Replace)
                throw new PolarsException($"No Delta table at {tablePath} to replace; use orCreate to create one.");
            // A catalog stages an empty location for a new table.
            if (existing is not null && features is not null) throw new PolarsException($"Table already exists at {tablePath} (a Delta table).");
            // Replaced, the table keeps the properties Spark keeps (the given ones win); a catalog-managed table also
            // keeps its id, as Spark keeps it.
            bool catalogOwned = existing is not null && CatalogManaged.IsCatalogManaged(existing.Protocol);
            if (existing is not null)
            {
                DeltaKernelWrite.RefuseConstraintProperties(configuration);
                configuration = Carried(existing.Metadata.Configuration, configuration, catalogOwned);
            }

            // The identity columns are declared on the schema first; column mapping (if on) then maps it whole.
            var declared = new Dictionary<string, KernelIdentityColumn>(StringComparer.Ordinal);
            foreach (KernelIdentityColumn column in identity)
            {
                if (schema.Field(column.Column) is null) throw new PolarsException($"The identity column '{column.Column}' is not in the schema.");
                if (partitions.Contains(column.Column)) throw new PolarsException($"The identity column '{column.Column}' cannot be a partition column.");
                if (!declared.TryAdd(column.Column, column)) throw new PolarsException($"The identity column '{column.Column}' is declared twice.");
            }
            var fields = schema.Fields.Select(f => declared.TryGetValue(f.Name, out KernelIdentityColumn? c)
                ? IdentityColumns.Declare(f, c.Start, c.Step, allowExplicitInsert: !c.GeneratedAlways)
                : f).ToList();
            StructType declaredSchema = DeclareExpressions(new StructType(fields), declared.Keys, generated ?? [], defaults ?? []);

            var (metadata, tableSchema) = DeltaKernelWrite.NewTableMetadata(
                declaredSchema, partitions, configuration, existing?.Metadata, catalogOwned ? existing!.Metadata.Id : null);
            ProtocolAction protocol = DeltaKernelWrite.ProtocolFor(tableSchema, metadata.Configuration);
            if (declared.Count > 0) protocol = TableFeatures.WithFeatures(protocol, [TableFeatures.IdentityColumns]);
            if (generated is { Count: > 0 }) protocol = TableFeatures.WithFeatures(protocol, [TableFeatures.GeneratedColumns]);
            if (defaults is { Count: > 0 }) protocol = TableFeatures.WithFeatures(protocol, [TableFeatures.AllowColumnDefaults]);
            List<StructField[]> clustered = Clustering.Resolve(tableSchema, clusterBy ?? [], partitions, metadata.Configuration);
            if (clustered.Count > 0) protocol = TableFeatures.WithFeatures(protocol, [Clustering.Feature]);
            if (features is not null) protocol = TableFeatures.WithFeatures(protocol, features);

            string operation = replacing switch
            {
                Replacing.No => "CREATE TABLE",
                Replacing.Replace => "REPLACE TABLE",
                _ => "CREATE OR REPLACE TABLE",
            };
            if (existing is not null)
            {
                RefuseUnboundConstraints(tableSchema, metadata.Configuration);
                RefuseDroppedChangeFeedColumns(existing, metadata, tableSchema, operation);
            }
            Transaction transaction;
            if (existing is null)
            {
                transaction = features is null
                    ? Transaction.Create(store, protocol, metadata, operation)
                    : Transaction.CreateCatalogManaged(store, protocol, metadata, operation).WithParameter("isManaged", "true");
            }
            else
            {
                // Every file goes; a concurrent commit makes this one fail (it changes the metadata).
                transaction = Transaction.Start(store, existing, operation).ReadPredicate(null).SetMetadata(metadata);
                ProtocolAction kept = AtLeast(existing.Protocol, protocol);
                if (!ReferenceEquals(kept, existing.Protocol)) transaction.SetProtocol(kept);
                long now = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
                foreach (AddAction file in existing.Files)
                    transaction.Add(new RemoveAction
                    {
                        Path = file.Path, DeletionTimestamp = now, DataChange = true, ExtendedFileMetadata = true,
                        PartitionValues = file.PartitionValues, Size = file.Size, DeletionVector = file.DeletionVector,
                        BaseRowId = file.BaseRowId, DefaultRowCommitVersion = file.DefaultRowCommitVersion,
                    });
                // A clustered table no longer clustered keeps an empty clustering domain, as Spark writes it.
                if (clustered.Count == 0 && existing.DomainMetadata.ContainsKey(Clustering.Domain)) transaction.Add(Clustering.DomainFor([]));
            }
            transaction
                .WithParameter("partitionBy", JsonText.StringArray(partitions))
                .WithParameter("clusterBy", JsonText.StringArray([.. clustered.Select(Clustering.LogicalName)]))
                .WithParameter("properties", JsonText.Object(configuration ?? new Dictionary<string, string>()));
            if (clustered.Count > 0) transaction.Add(Clustering.DomainFor(clustered.Select(Clustering.PhysicalPath)));
            return transaction.Commit();
        }
        catch (DeltaException e)
        {
            throw new PolarsException(e.Message, e);
        }
        finally
        {
            (store as IDisposable)?.Dispose();
        }
    }

    /// <summary>The key of the catalog's table id, which a catalog-managed table keeps when replaced.</summary>
    private const string CatalogTableIdKey = "io.unitycatalog.tableId";

    /// <summary>
    /// The properties a replaced table keeps, as Spark keeps them, under the given ones: deletion vectors and row
    /// tracking turned on (and the row tracking column names, so that the ids go on); a catalog-managed table keeps
    /// every <c>delta.*</c> property and its catalog's table id.
    /// </summary>
    private static Dictionary<string, string> Carried(IReadOnlyDictionary<string, string> old, IReadOnlyDictionary<string, string>? given, bool catalogOwned)
    {
        string[] keptKeys = [TableFeatures.EnableDeletionVectorsKey, RowTracking.EnableKey, RowTracking.MaterializedRowIdKey, RowTracking.MaterializedRowCommitVersionKey];
        var configuration = old
            .Where(p => catalogOwned
                ? p.Key.StartsWith("delta.", StringComparison.Ordinal) || p.Key == CatalogTableIdKey
                : keptKeys.Contains(p.Key, StringComparer.Ordinal))
            .ToDictionary(StringComparer.Ordinal);
        foreach (var (key, value) in given ?? new Dictionary<string, string>()) configuration[key] = value;
        return configuration;
    }

    /// <summary>
    /// Refuses a CHECK constraint the replaced table keeps that does not hold over the new schema (a column it reads is
    /// gone, say). Spark keeps it, and every write then fails on it.
    /// </summary>
    private static void RefuseUnboundConstraints(StructType schema, IReadOnlyDictionary<string, string> configuration)
    {
        foreach (var (key, expression) in configuration.Where(p => p.Key.StartsWith(Constraints.ConfigurationPrefix, StringComparison.Ordinal)))
        {
            if (DeltaConstraintCheck.Unenforceable(schema, expression) is { } reason)
                throw new PolarsException(
                    $"The table keeps its CHECK constraint '{key[Constraints.ConfigurationPrefix.Length..]}' ({expression}), which does not hold " +
                    $"over the new schema: {reason}. Drop it first (DropConstraint), then replace the table.");
        }
    }

    /// <summary>
    /// Refuses, as Spark does, a replacement that drops or renames a column of a table with rows, column mapping before
    /// and after, and the change data feed on in the new definition (a catalog-managed table keeps it; a table
    /// replaced by path keeps it only when given again): a column counts as dropped when the new schema does not keep
    /// its physical name (a column whose name or type changes gets a new one).
    /// </summary>
    private static void RefuseDroppedChangeFeedColumns(Snapshot existing, MetadataAction replacement, StructType schema, string operation)
    {
        if (existing.Files.Count == 0
            || TableFeatures.ColumnMappingModeOf(existing.Metadata) == ColumnMappingMode.None
            || TableFeatures.ColumnMappingModeOf(replacement) == ColumnMappingMode.None
            || !(replacement.Configuration.TryGetValue(ChangeFeed.EnableKey, out string? on) && string.Equals(on, "true", StringComparison.OrdinalIgnoreCase)))
            return;
        var kept = new HashSet<string>(StringComparer.Ordinal);
        Walk(schema, "", (field, _) => kept.Add(field.PhysicalName));
        List<string> dropped = [];
        Walk(existing.Schema, "", (field, path) => { if (!kept.Contains(field.PhysicalName)) dropped.Add(path); });
        if (dropped.Count == 0) return;
        throw new PolarsException(
            $"Operation \"{operation}\" is not allowed when the table has enabled change data feed (CDF) and has undergone schema changes " +
            $"using DROP COLUMN or RENAME COLUMN: the new schema drops or renames {string.Join(", ", dropped.Select(p => $"'{p}'"))} " +
            "(a column whose name or type changes counts as dropped). Keep those columns as they are, or delete the table's rows first.");

        static void Walk(DeltaType type, string path, Action<StructField, string> visit)
        {
            switch (type)
            {
                case StructType s:
                    foreach (StructField field in s.Fields)
                    {
                        string at = path.Length == 0 ? field.Name : $"{path}.{field.Name}";
                        visit(field, at);
                        Walk(field.Type, at, visit);
                    }
                    break;
                case ArrayType a:
                    Walk(a.ElementType, path + ".element", visit);
                    break;
                case MapType m:
                    Walk(m.KeyType, path + ".key", visit);
                    Walk(m.ValueType, path + ".value", visit);
                    break;
            }
        }
    }

    /// <summary>The table's protocol raised to support what <paramref name="needed"/> supports; never lowered.</summary>
    internal static ProtocolAction AtLeast(ProtocolAction current, ProtocolAction needed)
    {
        if (current.MinWriterVersion < 7 && needed.MinWriterVersion < 7)
            return needed.MinReaderVersion <= current.MinReaderVersion && needed.MinWriterVersion <= current.MinWriterVersion
                ? current
                : new ProtocolAction
                {
                    MinReaderVersion = Math.Max(current.MinReaderVersion, needed.MinReaderVersion),
                    MinWriterVersion = Math.Max(current.MinWriterVersion, needed.MinWriterVersion),
                };
        return TableFeatures.WithFeatures(current, [.. TableFeatures.WriterFeaturesOf(needed), .. TableFeatures.ReaderFeaturesOf(needed)]);
    }

    /// <summary>
    /// The schema with the generated columns' expressions and the columns' defaults in their fields' metadata, each
    /// checked as Spark checks it at <c>CREATE TABLE</c>: a top-level column of the schema, declared once, not an
    /// identity column, not both generated and defaulted; a generation expression deterministic, reading neither
    /// itself nor another generated column, of the column's type; a default a constant that can be stored in the column.
    /// </summary>
    /// <exception cref="PolarsException">A declaration is not valid.</exception>
    private static StructType DeclareExpressions(
        StructType schema, IEnumerable<string> identity, IReadOnlyList<DeltaGeneratedColumn> generated, IReadOnlyList<DeltaColumnDefault> defaults)
    {
        if (generated.Count == 0 && defaults.Count == 0) return schema;
        var identityColumns = identity.ToHashSet(StringComparer.Ordinal);
        var expressions = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
        void Declare(string column, string? expression, string what, string key)
        {
            ArgumentNullException.ThrowIfNull(column);
            if (schema.Field(column) is null)
                throw new PolarsException(column.Contains('.', StringComparison.Ordinal)
                    ? $"The {what} '{column}' is not a top-level column of the schema: only top-level columns can be one."
                    : $"The {what} '{column}' is not in the schema.");
            if (string.IsNullOrWhiteSpace(expression)) throw new PolarsException($"The {what} '{column}' has no expression.");
            if (identityColumns.Contains(column)) throw new PolarsException($"The {what} '{column}' is an identity column, which cannot also be one.");
            Dictionary<string, string> declared = expressions.TryGetValue(column, out var d) ? d : expressions[column] = [];
            if (declared.ContainsKey(key)) throw new PolarsException($"The {what} '{column}' is declared twice.");
            declared[key] = expression.Trim();
            if (declared.Count > 1)
                throw new PolarsException($"The column '{column}' cannot have both a default value and a generation expression.");
        }
        foreach (DeltaGeneratedColumn g in generated) Declare(g.Column, g.Expression, "generated column", Constraints.GenerationExpressionKey);
        foreach (DeltaColumnDefault d in defaults) Declare(d.Column, d.Expression, "column with a default", Constraints.CurrentDefaultKey);

        var result = new StructType([.. schema.Fields.Select(f => expressions.TryGetValue(f.Name, out var added) ? WithMetadata(f, added) : f)]);
        try
        {
            DeltaGeneratedColumns.Of(result, declaring: true);
        }
        catch (DeltaProtocolException e)
        {
            throw new PolarsException(e.Message, e);
        }
        foreach (var (column, added) in expressions)
            if (added.TryGetValue(Constraints.CurrentDefaultKey, out string? expression)) DeltaColumnDefaults.Validate(result, column, expression);
        return result;

        static StructField WithMetadata(StructField f, Dictionary<string, string> added) => new()
        {
            Name = f.Name, Type = f.Type, Nullable = f.Nullable, JsonMetadataKeys = f.JsonMetadataKeys,
            Metadata = new Dictionary<string, string>([.. f.Metadata, .. added], StringComparer.Ordinal),
        };
    }
}
