using Kaminari.Seseragi.Lakehouse.Delta;
using Kaminari.Seseragi.Lakehouse.Delta.Actions;
using Kaminari.Seseragi.Lakehouse.Delta.Schema;
using Kaminari.Seseragi.Lakehouse.Engine;
using Polars.NET.Core.Exceptions;

namespace Polars.NET.Core.Delta;

/// <summary>An identity column to declare when a table is created.</summary>
/// <param name="Column">The column; it must be a long (Int64) column of the schema, not a partition column.</param>
/// <param name="Start">The first value.</param>
/// <param name="Step">The distance between values; not 0 (negative counts down).</param>
/// <param name="GeneratedAlways">GENERATED ALWAYS (rows never bring their own value); false for GENERATED BY
/// DEFAULT (rows may bring one).</param>
internal sealed record KernelIdentityColumn(string Column, long Start = 1, long Step = 1, bool GeneratedAlways = true);

/// <summary>
/// Creates an empty Delta table, as Spark's <c>CREATE TABLE</c>: version 0 with the schema, partitioning, table
/// properties and identity columns given. The public Delta API calls it.
/// </summary>
internal static class DeltaKernelCreate
{
    /// <summary>Creates the table; returns its version, 0.</summary>
    /// <param name="tablePath">The table location: a local directory or a cloud URL.</param>
    /// <param name="schema">The columns.</param>
    /// <param name="partitionBy">Partition columns; null for none.</param>
    /// <param name="configuration">Table properties (they bring the features they turn on); null for none.</param>
    /// <param name="identity">Identity columns; null for none.</param>
    /// <param name="cloud">Cloud settings for a cloud URL.</param>
    /// <param name="clusterBy">Liquid clustering columns (dotted for nested fields); null for none.</param>
    /// <exception cref="PolarsException">A table exists at the path, or the declaration is not valid.</exception>
    public static long Create(
        string tablePath, StructType schema, string[]? partitionBy = null, IReadOnlyDictionary<string, string>? configuration = null,
        IReadOnlyList<KernelIdentityColumn>? identity = null, CloudArgs? cloud = null, string[]? clusterBy = null)
    {
        ArgumentNullException.ThrowIfNull(schema);
        if (schema.Fields.Count == 0) throw new PolarsException("A table needs at least one column.");
        string[] partitions = partitionBy ?? [];
        identity ??= [];
        IWritableFileSystem store = TableStorage.Open(tablePath, cloud).Store;
        try
        {
            if (DeltaKernelWrite.TryLoad(store, tablePath, cloud) is not null)
                throw new PolarsException($"Table already exists at {tablePath} (a Delta table).");

            // The identity columns are declared on the schema first; column mapping (if on) then maps it whole.
            var declared = new Dictionary<string, KernelIdentityColumn>(StringComparer.Ordinal);
            foreach (KernelIdentityColumn column in identity)
            {
                if (schema.Field(column.Column) is null) throw new PolarsException($"The identity column '{column.Column}' is not in the schema.");
                if (partitions.Contains(column.Column)) throw new PolarsException($"The identity column '{column.Column}' cannot be a partition column.");
                if (!declared.TryAdd(column.Column, column)) throw new PolarsException($"The identity column '{column.Column}' is declared twice.");
            }
            var fields = schema.Fields.Select(f => declared.TryGetValue(f.Name, out KernelIdentityColumn? c)
                ? IdentityColumns.Declare(f, c.Start, c.Step, allowExplicitInsert: !c.GeneratedAlways)
                : f).ToList();

            var (metadata, tableSchema) = DeltaKernelWrite.NewTableMetadata(new StructType(fields), partitions, configuration);
            ProtocolAction protocol = DeltaKernelWrite.ProtocolFor(tableSchema, metadata.Configuration);
            if (declared.Count > 0) protocol = TableFeatures.WithFeatures(protocol, [TableFeatures.IdentityColumns]);
            List<StructField[]> clustered = Clustering.Resolve(tableSchema, clusterBy ?? [], partitions, metadata.Configuration);
            if (clustered.Count > 0) protocol = TableFeatures.WithFeatures(protocol, [Clustering.Feature]);

            var transaction = Transaction.Create(store, protocol, metadata, "CREATE TABLE")
                .WithParameter("partitionBy", JsonText.StringArray(partitions))
                .WithParameter("clusterBy", JsonText.StringArray([.. clustered.Select(Clustering.LogicalName)]))
                .WithParameter("properties", JsonText.Object(configuration ?? new Dictionary<string, string>()));
            if (clustered.Count > 0) transaction.Add(Clustering.DomainFor(clustered.Select(Clustering.PhysicalPath)));
            return transaction.Commit();
        }
        catch (DeltaException e)
        {
            throw new PolarsException(e.Message, e);
        }
        finally
        {
            (store as IDisposable)?.Dispose();
        }
    }
}
