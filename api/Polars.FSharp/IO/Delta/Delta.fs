/// <summary>
/// Common Delta Lake Table Features.
/// </summary>
module DeltaTableFeatures =

    /// <summary>
    /// Enables Deletion Vectors for efficient deletes/updates (Merge-on-Read).
    /// Requires Reader v3, Writer v7.
    /// </summary>
    [<Literal>]
    let DeletionVectors = "deletionVectors"

    /// <summary>
    /// Enables Change Data Feed (CDF) to track row-level changes.
    /// </summary>
    [<Literal>]
    let ChangeDataFeed = "changeDataFeed"

    /// <summary>
    /// Enables Column Mapping (allows renaming columns and special characters).
    /// </summary>
    [<Literal>]
    let ColumnMapping = "columnMapping"

    /// <summary>
    /// Enforces Append-Only retention (prevents deletes/updates).
    /// </summary>
    [<Literal>]
    let AppendOnly = "appendOnly"
    
    /// <summary>
    /// Enables Check Constraints on columns.
    /// </summary>
    [<Literal>]
    let CheckConstraints = "checkConstraints"

    /// <summary>
    /// Enables TimestampWithoutTimezone.
    /// </summary>
    [<Literal>]
    let TimestampWithoutTimezone = "TimestampWithoutTimezone"

    /// <summary>
    /// Supports row tracking: every row gets a stable row id. Adding the feature gives new files row ids; set
    /// DeltaTableProperties.EnableRowTracking to make the ids of all rows stable.
    /// </summary>
    [<Literal>]
    let RowTracking = "rowTracking"

/// <summary>
/// Common configuration keys for Delta Tables.
/// </summary>
module DeltaTableProperties =

    /// <summary>
    /// The shortest duration that deleted files are kept before Vacuum deletes them.
    /// Default: 7 days (e.g., "interval 7 days").
    /// </summary>
    [<Literal>]
    let DeletedFileRetentionDuration = "delta.deletedFileRetentionDuration"

    /// <summary>
    /// How long the history of the Delta Log is kept.
    /// Default: 30 days (e.g., "interval 30 days").
    /// </summary>
    [<Literal>]
    let LogRetentionDuration = "delta.logRetentionDuration"

    /// <summary>
    /// The target file size in bytes for Optimize/Bin-packing.
    /// Default: 134217728 (128 MB).
    /// </summary>
    [<Literal>]
    let TargetFileSize = "delta.targetFileSize"

    /// <summary>
    /// Whether to collect stats for columns (min/max/nulls).
    /// Default: true.
    /// </summary>
    [<Literal>]
    let DataSkippingNumIndexedCols = "delta.dataSkippingNumIndexedCols"
    
    /// <summary>
    /// If true, enables the Change Data Feed (CDF).
    /// </summary>
    [<Literal>]
    let EnableChangeDataFeed = "delta.enableChangeDataFeed"

    /// <summary>
    /// If true, turns row tracking on: every row keeps a stable row id through updates, merges and optimize, read
    /// with the rowIdColumn and rowCommitVersionColumn options of ScanDelta. Set on an existing table, it gives the
    /// rows already there their ids.
    /// </summary>
    [<Literal>]
    let EnableRowTracking = "delta.enableRowTracking"

    /// <summary>
    /// If true, new files get no row ids although the table supports row tracking (the first step of turning it
    /// off). Cannot be true together with EnableRowTracking: set that to false in the same change. Set back to
    /// false, new files get ids again, after the highest id given so far.
    /// </summary>
    [<Literal>]
    let RowTrackingSuspended = "delta.rowTrackingSuspended"

    /// <summary>
    /// If true, new data, change data and deletion vector files go into directories of random letters and digits
    /// (Ab/part-…) instead of the partition directories, as Spark places them; the partition values are in the log.
    /// Spreading files over many prefixes avoids an object store's request limit per prefix. Tables with column
    /// mapping put their data and change data files under such prefixes without it, as Spark does.
    /// </summary>
    [<Literal>]
    let RandomizeFilePrefixes = "delta.randomizeFilePrefixes"

    /// <summary>The length of the random prefixes of RandomizeFilePrefixes, greater than 0. Default: 2.</summary>
    [<Literal>]
    let RandomPrefixLength = "delta.randomPrefixLength"

/// <summary>
/// An identity column to declare in Delta.CreateTable: a long (Int64) column whose values writes generate,
/// start, start + step, … (Spark's <c>GENERATED ALWAYS | BY DEFAULT AS IDENTITY (START WITH … INCREMENT BY …)</c>).
/// </summary>
/// <param name="column">The column: an Int64 column of the schema, not a partition column.</param>
/// <param name="start">The first value (1 by default).</param>
/// <param name="step">The distance between values (1 by default); not 0 (negative counts down).</param>
/// <param name="generatedAlways">True by default (GENERATED ALWAYS): writes may not bring values for the column.
/// False (GENERATED BY DEFAULT): rows that bring a value keep it, nulls included; values are generated only when
/// the written frame lacks the column.</param>
type DeltaIdentityColumn(column: string, ?start: int64, ?step: int64, ?generatedAlways: bool) =
    /// <summary>The column.</summary>
    member _.Column = column
    /// <summary>The first value.</summary>
    member _.Start = defaultArg start 1L
    /// <summary>The distance between values.</summary>
    member _.Step = defaultArg step 1L
    /// <summary>GENERATED ALWAYS (true) or BY DEFAULT (false).</summary>
    member _.GeneratedAlways = defaultArg generatedAlways true

/// <summary>
/// Methods for DeltaLake 
/// </summary>
type Delta =

    /// <summary>
    /// Creates an empty Delta table (version 0), as Spark's <c>CREATE TABLE</c>: the schema, partition columns,
    /// table properties and identity columns given. Writes then append to it; identity columns get their values
    /// generated (identity columns can only be declared when a table is created). Fails when a table exists at the
    /// path, or when a declaration is not valid.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="schema">The columns of the table.</param>
    /// <param name="partitionBy">Partition columns.</param>
    /// <param name="clusterBy">Liquid clustering columns (dotted for nested fields, at most four), as Spark's CLUSTER BY: Delta.Optimize clusters the table's data by them. Cannot be combined with partitionBy; the columns must be of a type with statistics and among the columns that get them.</param>
    /// <param name="properties">Table properties, such as DeltaTableProperties.EnableRowTracking; the features they turn on come into the protocol.</param>
    /// <param name="identityColumns">Identity columns.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member CreateTable(
        path: string,
        schema: PolarsSchema,
        ?partitionBy: seq<string>,
        ?clusterBy: seq<string>,
        ?properties: seq<string * string>,
        ?identityColumns: seq<DeltaIdentityColumn>,
        ?cloudOptions: CloudOptions
    ) =
        let props = defaultArg properties Seq.empty |> Seq.toArray
        let identity = defaultArg identityColumns Seq.empty |> Seq.toArray
        let cProv, cRet, cToMs, cInitMs, cMaxMs, cCache, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaCreateTable(
            path,
            schema.Handle,
            (match partitionBy with Some p -> Seq.toArray p | None -> null),
            (props |> Array.map fst),
            (props |> Array.map snd),
            (identity |> Array.map (fun c -> c.Column)),
            (identity |> Array.map (fun c -> c.Start)),
            (identity |> Array.map (fun c -> c.Step)),
            (identity |> Array.map (fun c -> c.GeneratedAlways)),
            cProv,
            cRet,
            cToMs,
            cInitMs,
            cMaxMs,
            cCache,
            cKeys,
            cVals,
            (match clusterBy with Some c -> Seq.toArray c | None -> null)
        )

    /// <summary>
    /// Changes the liquid clustering columns of a table, as Spark's ALTER TABLE … CLUSTER BY (no columns: CLUSTER BY
    /// NONE). A table that is not clustered becomes clustered; a partitioned one cannot. Data already clustered keeps
    /// its layout until Delta.Optimize with full; new data is clustered by the new columns.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="columns">The clustering columns, dotted for nested fields; at most four. Empty for none.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member ClusterBy(path: string, columns: seq<string>, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaClusterBy(path, Seq.toArray columns, cKeys, cVals)

    /// <summary>
    /// Renames a column, as Spark's ALTER TABLE … RENAME COLUMN: one metadata commit, no data is rewritten. Needs column
    /// mapping (set delta.columnMapping.mode to name first). Partition columns and the columns named in
    /// delta.dataSkippingStatsColumns are renamed with it.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="column">The column, any case; dotted for a nested field, with element for an array's element and key / value for a map's (items.element.price); a part holding a dot in backticks.</param>
    /// <param name="newName">The new name (of the last part, for a nested field). Names compare without regard to case: a name the struct already has, even differing only in case, is refused.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member RenameColumn(path: string, column: string, newName: string, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaRenameColumn(path, column, newName, cKeys, cVals)

    /// <summary>
    /// Drops columns, as Spark's ALTER TABLE … DROP COLUMNS: one metadata commit; the data stays in the files until they
    /// are rewritten (Delta.Purge) but is no longer read, and a column added later under the same name is a new column. Needs column
    /// mapping. Partition columns, clustering columns (and structs holding them) and the last column of the table or of
    /// a struct cannot be dropped.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="columns">The columns, named as in Delta.RenameColumn.</param>
    /// <param name="ifExists">Skip columns the table does not have instead of failing (no commit when none exists).</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member DropColumns(path: string, columns: seq<string>, ?ifExists: bool, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaDropColumns(path, Seq.toArray columns, defaultArg ifExists false, cKeys, cVals)

    /// <summary>
    /// Widens the type of a column, as Spark's ALTER TABLE … ALTER COLUMN … TYPE: one metadata commit; older files are
    /// read in their own type and cast. Needs type widening (set delta.enableTypeWidening to true first). Allowed:
    /// integers to wider integers or Float64 (from Int8, Int16, Int32) or a wide enough decimal, Float32 to Float64,
    /// decimals to wider decimals, Date to Datetime without a time zone (the table needs the timestampNtz feature).
    /// No commit when the column has the type already.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="column">The column, named as in Delta.RenameColumn; an array element or map key or value too.</param>
    /// <param name="dataType">The new type, as data of this type would be written (Int64 is Delta's long, and so on).</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member ChangeColumnType(path: string, column: string, dataType: DataType, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        use handle = dataType.CreateHandle()
        PolarsWrapper.DeltaChangeColumnType(path, column, handle, cKeys, cVals)

    /// <summary>
    /// Lets a column hold nulls, as Spark's ALTER TABLE … ALTER COLUMN … DROP NOT NULL: one metadata commit (also when
    /// the column already may). Delta has no way back: a nullable column cannot be made NOT NULL again, in Spark
    /// either. Identity columns and map keys cannot be changed.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="column">The column, named as in Delta.RenameColumn; element / value for the elements of an array or the values of a map.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member DropColumnNotNull(path: string, column: string, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaDropColumnNotNull(path, column, cKeys, cVals)

    /// <summary>
    /// Sets the comment of a column, as Spark's ALTER TABLE … ALTER COLUMN … COMMENT: one metadata commit; the comment
    /// is kept in the column's metadata (comment), where Spark, Databricks and Unity Catalog read it. Array elements
    /// and map keys and values take no comment.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="column">The column, named as in Delta.RenameColumn.</param>
    /// <param name="comment">The comment (empty is kept as an empty comment).</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member SetColumnComment(path: string, column: string, comment: string, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaSetColumnComment(path, column, comment, cKeys, cVals)

    /// <summary>
    /// Moves a column, or a field within its struct, as Spark's ALTER TABLE … ALTER COLUMN … FIRST / AFTER: one
    /// metadata commit that changes the order of the schema only (files hold columns by name, so no data is
    /// rewritten). Partition and clustering columns move too.
    /// </summary>
    /// <param name="path">The table location: a local directory or a cloud URL.</param>
    /// <param name="column">The column, named as in Delta.RenameColumn.</param>
    /// <param name="after">The column of the same struct to place it after, by its name only; omitted to place it first.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member MoveColumn(path: string, column: string, ?after: string, ?cloudOptions: CloudOptions) =
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        PolarsWrapper.DeltaMoveColumn(path, column, Option.toObj after, cKeys, cVals)

    /// <summary>
    /// Represents a column from the incoming Source LazyFrame.
    /// (Internally maps to "{name}_src_tmp")
    /// </summary>
    static member Source(columnName: string) =
        Expr.Col $"{columnName}_src_tmp"

    /// <summary>
    /// Represents a column from the existing Target Delta Table.
    /// (Alias for standard Col(), adds semantic clarity)
    /// </summary>
    static member Target(columnName: string) =
        Expr.Col columnName

    /// <summary>
    /// Deletes rows from a Delta Lake table that match a given predicate.
    /// <para>
    /// By default, this operation performs a Copy-on-Write (CoW), meaning any underlying data files containing matching rows are entirely rewritten.
    /// </para>
    /// <para>
    /// Note: If Deletion Vectors are enabled on the table, this operation automatically shifts to a Merge-on-Read (MoR) approach. 
    /// Instead of expensive file rewrites, deleted rows are swiftly marked in a separate deletion vector file, which drastically improves deletion performance.
    /// </para>
    /// </summary>
    /// <param name="path">Path to the Delta table.</param>
    /// <param name="predicate">Filter expression to identify rows to delete.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member Delete(
        path: string,
        predicate: Expr,
        ?cloudOptions: CloudOptions
    ) =
        // 1. Unpack Cloud Options
        let cProv, cRet, cToMs, cInitMs, cMaxMs, cCache, cKeys, cVals = 
            CloudOptions.ParseCloudOptions cloudOptions

        // 2. Safely clone the expression handle
        use clonedPredicate = predicate.CloneHandle()

        // 3. Native Call
        PolarsWrapper.DeltaDelete(
            path,
            clonedPredicate,
            cProv,
            cRet,
            cToMs,
            cInitMs,
            cMaxMs,
            cCache,
            cKeys,
            cVals
        )

    /// <summary>
    /// Updates the columns of the rows that match a predicate, as SQL <c>UPDATE table SET col = expr WHERE predicate</c>.
    /// <para>
    /// Each value is evaluated over the row before the update and cast to the column's type; a value that does not fit
    /// fails the update. Columns not named in <c>set</c> keep their values. With no predicate every row is updated.
    /// </para>
    /// <para>
    /// Identity columns cannot be updated; an update that sets one throws. Tables with deletion vectors, the change data
    /// feed or row tracking are handled as by <c>Delete</c>: with row tracking the updated rows keep their row ids.
    /// </para>
    /// </summary>
    /// <param name="path">Path to the Delta table.</param>
    /// <param name="set">Column names paired with the expressions of their new values.</param>
    /// <param name="predicate">Filter expression to identify rows to update; omit to update every row.</param>
    /// <param name="cloudOptions">Cloud storage configuration.</param>
    static member Update(
        path: string,
        set: seq<string * Expr>,
        ?predicate: Expr,
        ?cloudOptions: CloudOptions
    ) =
        let pairs = set |> Seq.toArray
        if String.IsNullOrEmpty path then raise (ArgumentException("The path is empty.", nameof path))
        if pairs.Length = 0 then raise (ArgumentException("An update sets at least one column.", nameof set))

        let cProv, cRet, cToMs, cInitMs, cMaxMs, cCache, cKeys, cVals =
            CloudOptions.ParseCloudOptions cloudOptions

        // The native call consumes the handles it is given.
        let columns = pairs |> Array.map fst
        let values = pairs |> Array.map (fun (_, value) -> value.CloneHandle())
        let clonedPredicate =
            match predicate with
            | Some p -> p.CloneHandle()
            | None -> null

        PolarsWrapper.DeltaUpdate(
            path,
            clonedPredicate,
            columns,
            values,
            cProv,
            cRet,
            cToMs,
            cInitMs,
            cMaxMs,
            cCache,
            cKeys,
            cVals
        )

    /// <summary>
    /// Recursively delete files and directories in the table that are no longer needed by the table for maintaining the transaction history.
    /// </summary>
    /// <param name="path">The root URI of the Delta table (e.g., "s3://bucket/table").</param>
    /// <param name="retentionHours">
    /// The retention threshold in hours. Files removed before this threshold will be deleted. 
    /// Set to -1 to use the default retention period configured in the table (usually 168 hours / 7 days).
    /// </param>
    /// <param name="enforceRetention">
    /// If true, prevents the vacuum command from deleting files that have not yet reached the retention threshold. 
    /// Setting this to false allows forcing deletion of recent files (use with caution).
    /// </param>
    /// <param name="dryRun">
    /// If true, simply returns the number of files that would be deleted, without actually deleting them.
    /// </param>
    /// <param name="vacuumModeFull">
    /// Specifies the vacuum mode:
    /// <para>false (Lite): Only removes files that are explicitly referenced as removed in the transaction log. Faster.</para>
    /// <para>true (Full): Scans the entire storage directory to find and remove any files not referenced in the transaction log (including orphan files from failed writes). Slower but more thorough.</para>
    /// </param>
    /// <param name="cloudOptions">Cloud storage credentials and configuration (e.g. AWS Keys, Azure Secrets).</param>
    /// <returns>The number of files deleted (or selected for deletion in dry-run mode).</returns>
    static member Vacuum(
        path: string,
        ?retentionHours: int,
        ?enforceRetention: bool,
        ?dryRun: bool,
        ?vacuumModeFull: bool,
        ?cloudOptions: CloudOptions
    ) : int64 =
        let pRetention = defaultArg retentionHours -1
        
        if retentionHours.IsSome && retentionHours.Value < 0 then
            invalidArg "retentionHours" "Retention hours cannot be negative."

        let pEnforce = defaultArg enforceRetention true
        let pDryRun = defaultArg dryRun false
        let pFull = defaultArg vacuumModeFull false

        // Vacuum doesn't need full retry mechanisms, just auth keys
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions

        PolarsWrapper.Vacuum(
            path,
            pRetention,
            pEnforce,
            pDryRun,
            pFull,
            cKeys,
            cVals
        )

    /// <summary>
    /// Restores the Delta table to a previous state defined by a specific version or timestamp.
    /// <para>Note: This operation creates a new commit (version) that reflects the state of the table at the target point.</para>
    /// </summary>
    /// <param name="path">The root URI of the Delta table.</param>
    /// <param name="version">The specific version number to restore to. Set to null if restoring by timestamp.</param>
    /// <param name="timestamp">The timestamp to restore to. Set to null if restoring by version.</param>
    /// <param name="ignoreMissingFiles">
    /// If true, the restore operation will ignore missing files (e.g., those deleted by Vacuum). 
    /// If false, it will fail if any required files are missing.
    /// </param>
    /// <param name="protocolDowngradeAllowed">Whether to allow downgrading the Delta Protocol version during restore (rarely needed).</param>
    /// <param name="cloudOptions">Cloud storage credentials.</param>
    /// <returns>The new version number of the table after the restore operation.</returns>
    static member Restore(
        path: string,
        ?version: uint64,
        ?timestamp: System.DateTime,
        ?ignoreMissingFiles: bool,
        ?protocolDowngradeAllowed: bool,
        ?cloudOptions: CloudOptions
    ) : uint64 =
        // 1. Validation: Version and Timestamp are mutually exclusive
        if version.IsSome && timestamp.IsSome then
            invalidArg "version/timestamp" "Cannot specify both 'version' and 'timestamp' for Restore."
        
        if version.IsNone && timestamp.IsNone then
            invalidArg "version/timestamp" "Must specify either 'version' or 'timestamp' for Restore."

        // 2. Prepare Parameters
        // Rust uses -1 to indicate "not set" for timestamp, and 0 for version
        let targetVer = defaultArg version 0UL
        
        let targetTs = 
            match timestamp with
            | Some dt -> 
                // Convert DateTime to Unix Milliseconds
                let utcTime = dt.ToUniversalTime()
                let ts = System.DateTimeOffset(utcTime).ToUnixTimeMilliseconds()
                
                // FFI Defense: Unix timestamp could theoretically be negative (pre-1970).
                // Since we use -1 as a sentinel, we must disallow timestamps before 1970-01-01 00:00:00.000 UTC.
                if ts < 0L then
                    invalidArg "timestamp" "Restore timestamp must be >= 1970-01-01T00:00:00.000Z"
                ts
            | None -> -1L

        let pIgnore = defaultArg ignoreMissingFiles false
        let pDowngrade = defaultArg protocolDowngradeAllowed false

        // 3. Parse Cloud Options
        // We only need keys/values for the Delta Lake object store
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions

        // 4. Call Wrapper
        PolarsWrapper.Restore(
            path,
            targetVer,
            targetTs,
            pIgnore,
            pDowngrade,
            cKeys,
            cVals
        )
    /// <summary>
    /// Returns provenance information, including the operation, user, timestamp, etc., for each write to a table.
    /// </summary>
    /// <param name="path">The root URI of the Delta table.</param>
    /// <param name="limit">The number of latest commits to retrieve. Set to 0 (default) to retrieve all history.</param>
    /// <param name="cloudOptions">Cloud storage credentials.</param>
    /// <returns>A DataFrame containing the commit history.</returns>
    static member History(
        path: string,
        ?limit: int,
        ?cloudOptions: CloudOptions
    ) : DataFrame =
        let pLimit = defaultArg limit 0
        let _, _, _, _, _, _, cKeys, cVals = CloudOptions.ParseCloudOptions cloudOptions
        
        // Fetch JSON string from Rust core
        let json = PolarsWrapper.History(path, pLimit, cKeys, cVals)
        let buffer = System.Text.Encoding.UTF8.GetBytes json
        
        let mutable df = DataFrame.ReadJson(buffer, jsonFormat = JsonFormat.Json, inferSchemaLen = 2000UL)

        // =========================================================
        // Post-Processing
        // =========================================================
        let cols = df.ColumnNames |> Seq.toList

        // i64 -> Datetime
        if Seq.contains "timestamp" cols then
            let expr = Expr.Col("timestamp").Cast((DataType.Datetime(TimeUnit.Milliseconds, "UCT"))).Alias "timestamp"
            df <- df.WithColumns [ expr :> IColumnExpr ]

        // operationParameters (Struct -> Columns)
        if Seq.contains "operationParameters" cols then
            df <- df.UnnestColumn "operationParameters"

        if Seq.contains "operationMetrics" cols then
            df <- df.UnnestColumn "operationMetrics"

        // Sort by version/timestamp
        if Seq.contains "version" cols then
            df <- df.Sort("version", descending = true)
        else
            df <- df.Sort("timestamp", descending = true)

        // Reorder columns to put priority info first
        let priorityCols = [| "version"; "timestamp"; "operation"; "mode"; "predicate"; "userName" |]
        let currentCols = df.ColumnNames |> Seq.toArray
        
        let selection = 
            priorityCols 
            |> Array.filter (fun c -> Array.contains c currentCols)
        
        let rest = 
            currentCols 
            |> Array.filter (fun c -> not (Array.contains c priorityCols))
            
        let finalCols = Array.append selection rest
        
        df.Select(finalCols |> Array.map Expr.Col |> Array.map (fun x -> x :> IColumnExpr))

    /// <summary>
    /// Optimizes the layout of the Delta table by compacting small files (bin-packing) and optionally applying Z-Order clustering.
    /// <para>
    /// This operation significantly improves read performance by reducing the number of files and co-locating related data.
    /// </para>
    /// <para>
    /// Note: If Deletion Vectors (DV) are enabled on the table, any soft-deleted rows tracked by the vectors 
    /// will be physically removed (materialized) from the newly compacted Parquet files, effectively clearing 
    /// the deletion vectors for the optimized partitions.
    /// </para>
    /// </summary>
    /// <param name="path">The root URI of the Delta table.</param>
    /// <param name="targetSizeMb">The target file size in Megabytes for the compacted files (default: 128 MB).</param>
    /// <param name="partitionFilters">
    /// Optional sequence of partition key-value pairs to restrict optimization to specific partitions.
    /// <para>Example: <c>[ ("date", "2024-01-01") ]</c></para>
    /// </param>
    /// <param name="zOrderColumns">
    /// Optional sequence of column names to apply Z-Order clustering. 
    /// <para>Z-Ordering co-locates data based on these columns, significantly speeding up queries that filter on them.</para>
    /// </param>
    /// <param name="cloudOptions">Cloud storage credentials and configuration.</param>
    /// <param name="full">On a table with liquid clustering, also recluster the data clustered by earlier clustering columns (Spark's OPTIMIZE FULL); without it only new data is clustered.</param>
    /// <returns>The number of new data files created during the optimization process.</returns>
